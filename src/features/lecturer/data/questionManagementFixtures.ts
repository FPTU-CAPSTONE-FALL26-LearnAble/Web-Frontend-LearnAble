function build(
  purpose: QuestionPurpose,
  seeds: readonly Seed[],
): ManagedQuestion[] {
  return seeds.map((seed, index) => ({
    id: `${purpose === "exam" ? "EXQ" : "PRQ"}-${String(index + 1).padStart(4, "0")}`,
    purpose,
    content: seed[0],
    subjectCode: seed[1],
    subjectName: seed[2],
    topic: seed[3],
    type: seed[4],
    difficulty: seed[5],
    score: seed[6],
    status: seed[7],
    usageCount: seed[8],
    readiness: seed[9],
    updatedAt: `2026-09-${String(18 - index).padStart(2, "0")}`,
  }));
}

